void              rsip_host_service(void);           /* poll mode: call in idle loop */
const rsip_host_stats_t *rsip_host_get_stats(void);
volatile rsip_hsm_shm_t *rsip_host_shm(void);
uint32_t          rsip_host_cycles_now(void);
void ISR_INTS2H0(void);

/* Host test (rsip_hsm_test.c) */
uint32_t rsip_test_run_all(void);                    /* returns fail count */
rsip_hsm_status_t rsip_host_request_led_dimming(uint32_t min_duty, uint32_t max_duty,
                                                uint32_t step, uint32_t frame_delay,
                                                uint32_t approved[4]);

